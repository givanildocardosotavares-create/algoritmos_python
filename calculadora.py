print("### CALCULADORA PYTHON ###")

def soma(num1, num2):
    soma = num1 + num2
    return soma

print("Resultado da soma: ", soma(16, 9))

def subtracao(num1, num2):
    subtracao = num1 - num2
    return subtracao

print("Resultado da subtração: ", subtracao(89,33)) 

def multiplicacao(num1, num2):
    multiplicacao = num1 * num2
    return multiplicacao

print("Resultado da multiplicação: ", multiplicacao(5, 6))

def divisao(num1, num2):
    divisao = num1 / num2
    return divisao

print("Resultado da divisão: ", divisao(10, 2))
